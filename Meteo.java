public class Meteo {
    private int vent;
    private int temp;
    private int precip;

    public int getVent() {
        return vent;
    }

    public void setVent(int vent) {
        this.vent = vent;
    }

    public int getTemp() {
        return temp;
    }

    public void setTemp(int temp) {
        this.temp = temp;
    }

    public int getPrecip() {
        return precip;
    }

    public void setPrecip(int precip) {
        this.precip = precip;
    }
}
